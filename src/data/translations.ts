function isSupportedLanguage(value: string | null): value is LanguageCode {
  return (
    value === 'en' ||
    value === 'en-US' ||
    value === 'es' ||
    value === 'de' ||
    value === 'fr' ||
    value === 'ja' ||
    value === 'pt'
  );
}

export function getSavedLanguage(): LanguageCode {
  if (typeof window === 'undefined') return 'en';
  try {
    const params = new URLSearchParams(window.location.search);
    const urlLang = params.get('lang');
    if (isSupportedLanguage(urlLang)) {
      return urlLang;
    }
    const stored = window.localStorage.getItem('portfolio_lang');
    if (isSupportedLanguage(stored)) {
      return stored;
    }
  } catch {
    // Ignore storage/URL errors in sandboxed iframes
  }
  return 'en';
}
